"""exp062 -- multi-dimensional atoms wired through the engine: an internal pacemaker drives action.

exp061 built multi-dimensional / oscillator atoms standalone. This wires them through the REAL
organism pipeline: ``Organism.step`` integrates a multi-dimensional atom (the scalar drive enters
its output dimension; the internal coupling defines its intrinsic dynamics; the global velocity
damping is not applied to it), and ``reset`` restores an oscillator's constructed phase rather than
collapsing it to rest. So a central pattern generator can live in an organism's atom set as a
first-class citizen, by the same force -> Verlet -> coupling machinery as every other atom.

Demonstration. We drop a CPG atom (``oscillator_atom``) into the default atom set and couple it to
the consummatory atom (one coupling entry), then run the organism with NO eliciting stimulus
(empty field). Result: the CPG free-runs (it oscillates inside the full pipeline), and the consume
atom -- with nothing in the environment driving it -- oscillates at the CPG's period (phase-lagged,
since the action atom integrates the rhythmic drive). That is spontaneous, periodic responding
generated by an internal pacemaker -- the form of adjunctive / interim behavior -- via the
engine's own dynamics. With the coupling removed, consume is flat: the rhythm is the CPG's doing.

Backward compatible: every default atom is scalar and byte-identical (reproduce exp001-030 same);
only an organism that is explicitly given a multi-dimensional atom uses the new path.

Run:  python experiments/exp062_cpg_in_organism.py
"""

from __future__ import annotations

from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import numpy as np  # noqa: E402

from behavioral_md.atoms import default_atom_set, oscillator_atom  # noqa: E402
from behavioral_md.config import SimulationConfig  # noqa: E402
from behavioral_md.forces import default_coupling_matrix  # noqa: E402
from behavioral_md.organism import Organism  # noqa: E402

FIG = Path("outputs/figures")
PERIOD = 30.0


def _neutral_obs() -> dict:
    z = np.zeros(2)
    o = {f"{s}_vector": z.copy() for s in ("food", "danger", "light", "cue")}
    o.update({f"{s}_intensity": np.array([0.0]) for s in ("food", "danger", "light", "cue")})
    o["food_contact"] = np.array([0.0])
    o["cue_value"] = np.array([0.0])
    o["context"] = np.array([0.0])
    return o


def run(cpg_gain: float, steps: int = 150) -> dict:
    """Run an organism (no stimulus) with a CPG atom coupled to consume at the given gain."""
    atoms = default_atom_set() + [oscillator_atom("rhythm", period=PERIOD, dt=0.1, amplitude=3.0)]
    idx = {a.name: i for i, a in enumerate(atoms)}
    coupling = default_coupling_matrix(atoms)
    if cpg_gain:
        coupling[idx["consume"], idx["rhythm"]] = cpg_gain        # CPG modulates consume
    org = Organism(SimulationConfig(seed=0, learning_rate=0.0), atoms=atoms,
                   coupling_matrix=coupling, rng=np.random.default_rng(0))
    obs = _neutral_obs()
    org.reset(obs)
    cpg, consume = [], []
    for _ in range(steps):
        org.step(obs)
        cpg.append(org.activation("rhythm"))
        consume.append(org.activation("consume"))
    return {"cpg": np.array(cpg), "consume": np.array(consume)}


def main() -> None:
    FIG.mkdir(parents=True, exist_ok=True)
    coupled = run(4.0)
    uncoupled = run(0.0)
    t = np.arange(coupled["cpg"].size)

    def period_of(x):
        zc = int((np.diff(np.sign(x - x.mean())) != 0).sum())
        return 2 * x.size / max(zc, 1)

    p_cpg = period_of(coupled["cpg"])
    p_con = period_of(coupled["consume"])
    print("Multi-dimensional atom wired through the organism:\n")
    print(f"A. a CPG atom integrated by the full pipeline free-runs: period ~{p_cpg:.0f} steps, "
          f"amplitude {coupled['cpg'].max():.1f}.")
    print(f"B. coupled to consume (no eliciting stimulus): consume oscillates at the SAME period "
          f"~{p_con:.0f} steps (amplitude {coupled['consume'].max():.2f}) -- spontaneous rhythmic "
          f"responding; with the coupling removed consume std = {uncoupled['consume'].std():.3f} "
          "(flat).")

    fig, ax = plt.subplots(1, 2, figsize=(12.5, 4.5))

    ax[0].plot(t, coupled["cpg"], color="tab:blue", lw=2, label="CPG atom (pacemaker)")
    ax[0].plot(t, coupled["consume"], color="tab:purple", lw=2, label="consume (behavior)")
    ax[0].axhline(0, color="0.85", lw=0.8)
    ax[0].set_xlabel("step")
    ax[0].set_ylabel("activation")
    ax[0].set_title("A. A CPG atom wired through the organism drives\nrhythmic responding "
                    "(consume tracks its period)")
    ax[0].legend(fontsize=8, loc="upper right")

    ax[1].plot(t, uncoupled["consume"], color="tab:gray", lw=2, label="no CPG coupling (flat)")
    ax[1].plot(t, coupled["consume"], color="tab:purple", lw=2, label="CPG-coupled (rhythmic)")
    ax[1].axhline(0, color="0.85", lw=0.8)
    ax[1].set_xlabel("step")
    ax[1].set_ylabel("consume activation")
    ax[1].set_title("B. No eliciting stimulus: the pacemaker\nis the source of the periodic "
                    "behavior")
    ax[1].legend(fontsize=8, loc="upper right")

    fig.tight_layout()
    out = FIG / "exp062_cpg_in_organism.png"
    fig.savefig(out, dpi=130, bbox_inches="tight")
    plt.close(fig)
    print(f"\nwrote {out}")


if __name__ == "__main__":
    main()
